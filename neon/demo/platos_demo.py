def slug(texto):
    tabla = str.maketrans("áéíóúñü ", "aeiounu_")
    return "punto_" + texto.lower().translate(tabla)


def armar(i, plato):
    """Devuelve el SVG y los datos (macros y puntos) de un plato."""
    nombre, desc, tags, zonas, centro, momento = plato
    svg, pos = d.plato_svg(1000 + i, [ING[k][6] for k in zonas], ING[centro][6] if centro else None)
    claves = zonas + ([centro] if centro else [])
    macros = [sum(ING[k][2][j] for k in claves) for j in range(4)]
    puntos = []
    for orden, (k, (x, y)) in enumerate(zip(claves, pos)):
        nom, cat, (kcal, *_), aporte, ben, etq, _ = ING[k]
        puntos.append({"id": slug(nom), "nombre": nom, "categoria": cat, "aporte": aporte, "kcal": f"{kcal} kcal",
                       "x": x, "y": y, "orden": orden, "beneficios": ben, "etiquetas": etq})
    return svg, {"nombre": nombre, "descripcion": desc, "tags": tags, "macros": macros, "puntos": puntos, "momento": momento}
